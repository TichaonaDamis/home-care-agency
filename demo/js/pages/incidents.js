import { api } from '../api.js';
import { esc, table, tabs, badge, fields, readForm, opts, fmtDT, fmtDate, fmtISO, label, formModal, toast, showError, addDays } from '../ui.js';
import { incidentDialog, INCIDENT_TYPES, TRANSITION_TYPES } from './shared.js';

const TABS = [['alerts', 'Alerts'], ['incidents', 'Incident reports'], ['transitions', 'Hospital & hospice events']];

export async function render(el, parts, query, ctx) {
  const tab = query.tab || 'alerts';
  const clients = await api.get('/clients');
  el.innerHTML = `<div class="page-head"><div><h1>Incidents & Alerts</h1><p>Every alert is tracked from creation through acknowledgement, escalation and resolution.</p></div>
    <div class="page-actions"><button class="btn primary" id="report">+ Report incident</button></div></div>
    ${tabs(TABS.filter(([k]) => (k === 'alerts' ? ctx.can('alerts.manage') : k === 'incidents' ? ctx.can('incidents.manage') : ctx.can('transitions.manage', 'clients.view'))), tab)}<div id="tab"></div>`;
  el.querySelector('.tabs').addEventListener('click', (e) => { const t = e.target.closest('[data-tab]'); if (t) location.hash = `#/incidents?tab=${t.dataset.tab}`; });
  const reload = () => render(el, parts, query, ctx);
  el.querySelector('#report').addEventListener('click', async () => {
    const now = new Date();
    const local = new Date(now.getTime() - now.getTimezoneOffset() * 60000).toISOString().slice(0, 16);
    if (await incidentDialog({ clients, now: local })) reload();
  });
  const box = el.querySelector('#tab');
  const filt = (defs) => `<form class="filters" id="filters">${fields(defs)}</form>`;
  const onFilter = () => box.querySelector('#filters')?.addEventListener('change', (e) => { location.hash = `#/incidents${api.qs({ tab, ...readForm(e.currentTarget) })}`; });

  if (tab === 'alerts') {
    const status = query.status || 'unresolved';
    const rows = await api.get('/alerts', { status, client_id: query.client_id, severity: query.severity, category: query.category });
    box.innerHTML = `<section class="card">${filt([
      { name: 'status', label: 'Status', type: 'select', required: true, options: [['unresolved', 'Unresolved'], ['open', 'Open (unacknowledged)'], ['acknowledged', 'Acknowledged'], ['escalated', 'Escalated'], ['resolved', 'Resolved']], value: status },
      { name: 'client_id', label: 'Client', type: 'select', options: opts(clients, 'legal_name'), value: query.client_id },
      { name: 'severity', label: 'Severity', type: 'select', options: ['high', 'medium', 'low', 'info'].map((s) => [s, label(s)]), value: query.severity },
      { name: 'category', label: 'Category', type: 'select', options: ['measurement', 'nutrition', 'hydration', 'fall', 'medication', 'incident', 'transition', 'trend', 'pain', 'condition_change'].map((s) => [s, label(s)]), value: query.category },
    ])}
    ${table([
      { label: 'Raised', render: (a) => fmtISO(a.created_at) },
      { label: 'Client', render: (a) => (a.client_id ? `<a href="#/clients/${a.client_id}?tab=progress">${esc(a.client_name)}</a>` : '—') },
      { label: 'Alert', cls: 'wrap', render: (a) => `${badge(a.severity)} ${badge('info', label(a.category))}<div>${esc(a.message)}</div>${a.escalation ? `<div class="sub"><strong>Escalation:</strong> ${esc(a.escalation)}</div>` : ''}` },
      { label: 'Status', render: (a) => `${badge(a.status)}${a.acknowledged_at ? `<div class="sub">ack ${esc(a.acknowledged_by_name)} ${fmtISO(a.acknowledged_at)}</div>` : ''}${a.escalated_at ? `<div class="sub">esc. ${esc(a.escalated_by_name)}: ${esc(a.escalation_note)}</div>` : ''}${a.resolved_at ? `<div class="sub">resolved ${esc(a.resolved_by_name)}: ${esc(a.resolution)}</div>` : ''}` },
      { label: '', render: (a) => (a.status === 'resolved' ? '' : `${a.status === 'open' ? `<button class="btn link" data-a="acknowledge" data-id="${a.id}">Acknowledge</button>` : ''}<button class="btn link" data-a="escalate" data-id="${a.id}">Escalate</button><button class="btn link" data-a="resolve" data-id="${a.id}">Resolve</button>`) },
    ], rows, { empty: status === 'unresolved' ? 'No unresolved alerts. ✓' : 'No alerts match.' })}
    <p class="disclaimer">Alerts are generated by configurable rules from documented records. They support — not replace — clinical judgment and emergency procedures.</p></section>`;
    box.addEventListener('click', async (e) => {
      const { a, id } = e.target.dataset;
      if (!a) return;
      try {
        if (a === 'acknowledge') await api.post(`/alerts/${id}/acknowledge`);
        else if (!await formModal({ title: a === 'escalate' ? 'Escalate alert' : 'Resolve alert', defs: [{ name: 'note', label: a === 'escalate' ? 'Who was contacted, how, and their instructions' : 'Resolution / follow-up documented', type: 'textarea', required: true, full: true }], submit: (v) => api.post(`/alerts/${id}/${a}`, v) })) return;
        toast('Alert updated.', 'ok');
        ctx.refreshNotifications();
        reload();
      } catch (err) { showError(err); }
    });
  }

  if (tab === 'incidents') {
    const rows = await api.get('/incidents', { status: query.status, client_id: query.client_id, severity: query.severity, type: query.type, from: query.from, to: query.to });
    box.innerHTML = `<section class="card">${filt([
      { name: 'status', label: 'Status', type: 'select', options: [['open', 'Open'], ['under_review', 'Under review'], ['closed', 'Closed']], value: query.status },
      { name: 'severity', label: 'Severity', type: 'select', options: ['low', 'moderate', 'high', 'critical'].map((s) => [s, label(s)]), value: query.severity },
      { name: 'type', label: 'Type', type: 'select', options: INCIDENT_TYPES.map((s) => [s, label(s)]), value: query.type },
      { name: 'client_id', label: 'Client', type: 'select', options: opts(clients, 'legal_name'), value: query.client_id },
      { name: 'from', label: 'From', type: 'date', value: query.from }, { name: 'to', label: 'To', type: 'date', value: query.to },
    ])}
    ${table([
      { label: 'Occurred', render: (i) => fmtDT(i.occurred_at) },
      { label: 'Client', render: (i) => esc(i.client_name || '—') },
      { label: 'Incident', cls: 'wrap', render: (i) => `${badge(i.severity)} <strong>${esc(label(i.type))}</strong><div>${esc(i.description)}</div>${i.immediate_action ? `<div class="sub">Action: ${esc(i.immediate_action)}</div>` : ''}${i.notified ? `<div class="sub">Notified: ${esc(i.notified)}</div>` : ''}` },
      { label: 'Reported by', render: (i) => esc(i.reporter) },
      { label: 'Status / follow-up', cls: 'wrap', render: (i) => `${badge(i.status)}${i.follow_up ? `<div class="sub">${esc(i.follow_up)}</div>` : ''}${i.reviewer ? `<div class="sub">Reviewed by ${esc(i.reviewer)}</div>` : ''}` },
      { label: '', render: (i) => (i.status !== 'closed' ? `<button class="btn link" data-inc="${i.id}">Review</button>` : '') },
    ], rows, { empty: 'No incidents match.' })}</section>`;
    box.addEventListener('click', async (e) => {
      const id = e.target.dataset.inc;
      if (!id) return;
      const i = rows.find((x) => x.id === Number(id));
      if (await formModal({
        title: 'Review incident',
        defs: [{ name: 'status', label: 'Status', type: 'select', required: true, options: [['open', 'Open'], ['under_review', 'Under review'], ['closed', 'Closed']] }, { name: 'severity', label: 'Severity', type: 'select', required: true, options: ['low', 'moderate', 'high', 'critical'].map((s) => [s, label(s)]) }, { name: 'follow_up', label: 'Follow-up / corrective action', type: 'textarea', full: true, rows: 4 }],
        values: i, submit: (v) => api.patch(`/incidents/${id}`, v),
      })) reload();
    });
  }

  if (tab === 'transitions') {
    const rows = await api.get('/transitions', { event_type: query.event_type, client_id: query.client_id, follow_up_pending: query.follow_up_pending, from: query.from || addDays(ctx.today(), -90), to: query.to });
    const lbl = Object.fromEntries(TRANSITION_TYPES);
    box.innerHTML = `<section class="card">${filt([
      { name: 'event_type', label: 'Event', type: 'select', options: TRANSITION_TYPES, value: query.event_type },
      { name: 'client_id', label: 'Client', type: 'select', options: opts(clients, 'legal_name'), value: query.client_id },
      { name: 'follow_up_pending', label: 'Follow-up', type: 'select', options: [['1', 'Pending follow-up only']], value: query.follow_up_pending },
      { name: 'from', label: 'From', type: 'date', value: query.from || addDays(ctx.today(), -90) },
    ])}
    ${table([
      { label: 'Date', render: (t) => fmtDate(t.event_date) },
      { label: 'Client', render: (t) => `<a href="#/clients/${t.client_id}?tab=transitions">${esc(t.client_name)}</a>` },
      { label: 'Event', render: (t) => `<strong>${esc(lbl[t.event_type])}</strong>` },
      { label: 'Details', cls: 'wrap', render: (t) => esc([t.location, t.provider, t.notes].filter(Boolean).join(' · ')) },
      { label: 'Source', render: (t) => esc(t.source || '') },
      { label: 'Follow-up', render: (t) => (t.follow_up_due ? `${fmtDate(t.follow_up_due)} ${t.follow_up_done ? badge('complete', 'Done') : badge('pending')}` : '—') },
    ], rows, { empty: 'No care transitions in this period.' })}
    <p class="hint">Record new events from the client’s “Care transitions” tab.</p></section>`;
  }
  onFilter();
}
